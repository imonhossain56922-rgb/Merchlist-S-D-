import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { MockupRequest } from '../types';
import { formatDateInTimezone } from './dateUtils';

interface GenerateReportPdfParams {
  requests: MockupRequest[];
  dateRangeLabel: string;
  appliedFilters: {
    roleFilter?: string;
    statusFilter?: string;
    priorityFilter?: string;
    sourceFilter?: string;
    searchQuery?: string;
  };
  generatedByName: string;
  timezone: string;
  companyName?: string;
  applicationName?: string;
}

export function generateReportPdf(params: {
  requests: MockupRequest[];
  dateRangeLabel: string;
  appliedFilters: {
    status?: string;
    priority?: string;
    source?: string;
    salesRep?: string;
    designer?: string;
  };
  generatedByName: string;
  timezone: string;
  companyName?: string;
  applicationName?: string;
}): void {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const appName = params.applicationName || 'Marchlist Mockup Request';
  const companyName = params.companyName || 'Merchlist';
  const nowStr = formatDateInTimezone(new Date(), params.timezone, true);

  // Corporate Dark Navy Header Box
  doc.setFillColor(12, 25, 44); // #0c192c
  doc.rect(0, 0, 842, 60, 'F');

  // Brand Name & Subtitle
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(companyName.toUpperCase(), 36, 32);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(0, 210, 211); // Teal accent
  doc.text(appName.toUpperCase(), 36, 47);

  // Right-aligned report label & generation info
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(255, 255, 255);
  doc.text('OFFICIAL OPERATIONS REPORT', 806, 28, { align: 'right' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(200, 210, 225);
  doc.text(`Generated: ${nowStr} (${params.timezone})`, 806, 44, { align: 'right' });

  // Metadata card below header
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.rect(36, 75, 770, 48, 'FD');

  doc.setTextColor(71, 85, 105); // slate-600
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text(`Date Range: ${params.dateRangeLabel}`, 48, 93);
  doc.text(`Generated By: ${params.generatedByName}`, 48, 110);

  // Active filters summary
  const filtersApplied = [
    params.appliedFilters.status ? `Status: ${params.appliedFilters.status}` : '',
    params.appliedFilters.priority ? `Priority: ${params.appliedFilters.priority}` : '',
    params.appliedFilters.source ? `Source: ${params.appliedFilters.source}` : '',
    params.appliedFilters.salesRep ? `Sales: ${params.appliedFilters.salesRep}` : '',
    params.appliedFilters.designer ? `Designer: ${params.appliedFilters.designer}` : '',
  ]
    .filter(Boolean)
    .join('  |  ') || 'All Records';

  doc.setFont('helvetica', 'normal');
  doc.text(`Applied Filters: ${filtersApplied}`, 360, 93);

  // Compute metrics
  const total = params.requests.length;
  const completed = params.requests.filter((r) => r.status === 'COMPLETED').length;
  const pending = params.requests.filter((r) => r.status === 'PENDING').length;
  const rejected = params.requests.filter((r) => r.status === 'REJECTED').length;
  const rate = total > 0 ? Math.round((completed / total) * 100) : 0;

  doc.setFont('helvetica', 'bold');
  doc.text(`Total: ${total}   |   Completed: ${completed}   |   Pending: ${pending}   |   Rate: ${rate}%`, 360, 110);

  // Prepare table data
  const tableRows = params.requests.map((req) => {
    const createdStr = formatDateInTimezone(req.createdAt, params.timezone, true);
    const completedStr = req.completedAt
      ? formatDateInTimezone(req.completedAt, params.timezone, true)
      : 'Not Completed';

    return [
      req.requestId,
      req.mockupTitle || (req.source === 'gallabox' ? 'Gallabox Request' : '-'),
      req.itemName || (req.source === 'gallabox' ? 'N/A' : '-'),
      req.salesRepresentativeName,
      req.designerName,
      createdStr,
      completedStr,
      req.status,
      req.priority.replace('_', ' '),
    ];
  });

  autoTable(doc, {
    startY: 136,
    head: [
      [
        'Request ID',
        'Mockup Title',
        'Item',
        'Sales Rep',
        'Designer',
        'Created',
        'Completed',
        'Status',
        'Priority',
      ],
    ],
    body: tableRows.length > 0 ? tableRows : [['-', 'No mockup requests found', '-', '-', '-', '-', '-', '-', '-']],
    theme: 'grid',
    headStyles: {
      fillColor: [12, 25, 44],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
      halign: 'left',
    },
    styles: {
      fontSize: 8,
      cellPadding: 5,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.5,
    },
    alternateRowStyles: {
      fillColor: [250, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 55, fontStyle: 'bold' },
      1: { cellWidth: 135 },
      2: { cellWidth: 80 },
      3: { cellWidth: 85 },
      4: { cellWidth: 85 },
      5: { cellWidth: 95 },
      6: { cellWidth: 95 },
      7: { cellWidth: 65 },
      8: { cellWidth: 75 },
    },
    margin: { left: 36, right: 36, bottom: 45 },
    didDrawPage: (data) => {
      // Footer on all pages
      const pageCount = doc.getNumberOfPages();
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184); // slate-400
      doc.text(
        `${appName} - Confidential Internal Document - Page ${data.pageNumber} of ${pageCount}`,
        421,
        575,
        { align: 'center' }
      );
    },
  });

  // Save the PDF
  const filename = `${companyName}_Mockup_Report_${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(filename);
}
